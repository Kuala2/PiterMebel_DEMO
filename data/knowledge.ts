const WORD_PATTERN = /[\p{L}\p{N}][\p{L}\p{N}–—-]*/gu;

export function getArticleWordCount(article: KnowledgeArticle) {
  const visibleText = [
    article.categoryLabel,
    article.title,
    article.excerpt,
    article.publishedAt,
    article.author.name,
    article.author.role,
    ...article.keyTakeaways,
    ...(article.tableOfContents?.map((item) => item.title) ?? []),
    ...article.sections.flatMap((section) => [
      section.heading,
      ...section.text,
      ...(section.list?.items.flatMap((item) => [item.lead, item.label ?? "", item.body]) ?? []),
      section.callout?.title ?? "",
      section.callout?.body ?? "",
      ...(section.table?.headers ?? []),
      ...(section.table?.rows.flat() ?? []),
      section.figure?.caption ?? "",
    ]),
    ...article.faq.flatMap((item) => [item.question, item.answer]),
    ...article.sources.flatMap((source) => [source.title, source.note]),
    ...article.relatedLinks.flatMap((link) => [link.title, link.description]),
    ...(article.caseStudy
      ? [article.caseStudy.title, article.caseStudy.task, article.caseStudy.conflict, article.caseStudy.solution]
      : []),
  ].join(" ");

  return visibleText.match(WORD_PATTERN)?.length ?? 0;
}

export function getArticleReadTime(article: KnowledgeArticle) {
  return Math.max(1, Math.ceil(getArticleWordCount(article) / 180));
}

export function getArticleBySlug(slug: string): KnowledgeArticle | undefined {
  return KNOWLEDGE_ARTICLES.find((a) => a.slug === slug);
}

export function getArticlesByCategory(category?: string): KnowledgeArticle[] {
  if (!category || category === "all") return KNOWLEDGE_ARTICLES;
  return KNOWLEDGE_ARTICLES.filter((a) => a.category === category);
}
